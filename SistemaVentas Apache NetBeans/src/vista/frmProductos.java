for (Producto producto
        : ProductoController.buscarProductos(texto)) {

    modeloTabla.addRow(new Object[]{
        producto.getIdProducto(),
        producto.getNombre(),
        producto.getPrecio(),
        producto.getExistencia()
    });
}
