    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
       String nombre = txtNombre.getText().trim();
    String precioTexto = txtPrecio.getText().trim();
    String stockTexto = txtStock.getText().trim();

    if (nombre.isEmpty()
            || precioTexto.isEmpty()
            || stockTexto.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Complete todos los campos."
        );

        return;
    }

    try {

        double precio = Double.parseDouble(precioTexto);
        int stock = Integer.parseInt(stockTexto);

        if (precio < 0 || stock < 0) {

            JOptionPane.showMessageDialog(
                    this,
                    "El precio y el stock no pueden ser negativos."
            );

            return;
        }

        Producto producto = new Producto(
                0,
                nombre,
                precio,
                stock
        );

        boolean resultado =
                ProductoController.guardarProducto(producto);

        if (resultado) {

            JOptionPane.showMessageDialog(
                    this,
                    "Producto guardado correctamente."
            );

            limpiarCampos();
            cargarProductos();

        } else {

            JOptionPane.showMessageDialog(
                    this,
                    "No se pudo guardar el producto."
            );
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Precio y stock deben ser valores numéricos."
        );
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblProductosMouseClicked
        int fila = tblProductos.getSelectedRow();

if (fila >= 0) {

    idProductoSeleccionado =
            Integer.parseInt(
                    tblProductos.getValueAt(fila, 0).toString()
            );

    txtCodigo.setText(
            tblProductos.getValueAt(fila, 0).toString()
    );

    txtNombre.setText(
            tblProductos.getValueAt(fila, 1).toString()
    );

    txtPrecio.setText(
            tblProductos.getValueAt(fila, 2).toString()
    );

    txtStock.setText(
            tblProductos.getValueAt(fila, 3).toString()
    );
}
    }//GEN-LAST:event_tblProductosMouseClicked

