private void calcularTotal() {

    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalle.getModel();

    total = 0;

    for (int i = 0; i < modelo.getRowCount(); i++) {

        double subtotal = Double.parseDouble(
                modelo.getValueAt(i, 4).toString()
        );

        total += subtotal;
    }

    txtTotal.setText(
            String.format("%.2f", total)
    );
}
private int obtenerIdClienteSeleccionado() {

    int indice = cmbCliente.getSelectedIndex();

    if (indice < 0 || clientes == null
            || indice >= clientes.size()) {

        return -1;
    }

    return clientes.get(indice).getIdCliente();
}
    
