    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
         Producto producto = obtenerProductoSeleccionado();

    if (producto == null) {

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un producto."
        );

        return;
    }

    int cantidad;

    try {

        cantidad = Integer.parseInt(
                txtCantidad.getText().trim()
        );

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese una cantidad válida."
        );

        return;
    }

    if (cantidad <= 0) {

        JOptionPane.showMessageDialog(
                this,
                "La cantidad debe ser mayor que cero."
        );

        return;
    }

    if (cantidad > producto.getExistencia()) {

        JOptionPane.showMessageDialog(
                this,
                "No hay suficiente existencia.\n"
                + "Existencia disponible: "
                + producto.getExistencia()
        );

        return;
    }

    double precio = producto.getPrecio();

    double subtotal = cantidad * precio;

    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalle.getModel();

    // Verificar si el producto ya está agregado
    for (int i = 0; i < modelo.getRowCount(); i++) {

        int idExistente = Integer.parseInt(
                modelo.getValueAt(i, 0).toString()
        );

        if (idExistente == producto.getIdProducto()) {

            JOptionPane.showMessageDialog(
                    this,
                    "El producto ya está agregado a la venta."
            );

            return;
        }
    }

    modelo.addRow(new Object[]{
        producto.getIdProducto(),
        producto.getNombre(),
        cantidad,
        precio,
        subtotal
    });

    calcularTotal();

    txtCantidad.setText("1");
    txtSubtotal.setText("0.00");
    }//GEN-LAST:event_btnAgregarActionPerformed

