    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
   int idCliente = obtenerIdClienteSeleccionado();

    if (idCliente == -1) {

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un cliente."
        );

        return;
    }

    DefaultTableModel modelo =
            (DefaultTableModel) tblDetalle.getModel();

    if (modelo.getRowCount() == 0) {

        JOptionPane.showMessageDialog(
                this,
                "Agregue al menos un producto."
        );

        return;
    }

    List<DetalleVenta> detalles =
            new ArrayList<>();

    for (int i = 0; i < modelo.getRowCount(); i++) {

        int idProducto = Integer.parseInt(
                modelo.getValueAt(i, 0).toString()
        );

        int cantidad = Integer.parseInt(
                modelo.getValueAt(i, 2).toString()
        );

        double precio = Double.parseDouble(
                modelo.getValueAt(i, 3).toString()
        );

        double subtotal = Double.parseDouble(
                modelo.getValueAt(i, 4).toString()
        );

        DetalleVenta detalle =
                new DetalleVenta();

        detalle.setIdProducto(idProducto);
        detalle.setCantidad(cantidad);
        detalle.setPrecio(precio);
        detalle.setSubtotal(subtotal);

        detalles.add(detalle);
    }

    boolean resultado =
            ventaController.registrarVenta(
                    idCliente,
                    total,
                    detalles
            );

    if (resultado) {

        JOptionPane.showMessageDialog(
                this,
                "Venta registrada correctamente."
        );

        limpiarVenta();

        cargarProductos();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "No se pudo registrar la venta.\n"
                + "Verifique la existencia de los productos."
        );
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

